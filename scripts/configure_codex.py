"""Generate checkout-local Codex settings without replacing user customizations."""
import hashlib
import json
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by scripts/configure_codex.py; SHA256="


def render(root):
    root = root.resolve()
    env = {
        "PATH": f"{root}/.venv/bin:{root}/.local/mise_home/data/shims:{root}/.local/mise_home/bin:{root}/.local/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin",
        "MISE_DATA_DIR": str(root / ".local/mise_home/data"),
        "MISE_CACHE_DIR": str(root / ".local/mise_home/cache"),
        "MISE_STATE_DIR": str(root / ".local/mise_home/state"),
        "MISE_CONFIG_DIR": str(root / ".local/mise_home/config"),
        "XDG_CACHE_HOME": str(root / ".local/cache"),
        "PIP_CACHE_DIR": str(root / ".local/cache/pip"),
        "TMPDIR": str(root / ".local/tmp"),
        "PYTHONPYCACHEPREFIX": str(root / ".local/cache/pycache"),
    }
    body = "allow_login_shell = false\n\n[shell_environment_policy.set]\n"
    body += "".join(f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in env.items())
    return MARKER + hashlib.sha256(body.encode()).hexdigest() + "\n" + body


def configure(root):
    target = root / ".codex/config.toml"
    desired = render(root)
    if target.is_symlink():
        raise ValueError(f"Refusing to replace symlink: {target}")
    if target.parent.is_symlink():
        raise ValueError(f"Refusing to write through symlink: {target.parent}")
    if target.exists():
        existing = target.read_text()
        if existing == desired:
            return target
        header, _, body = existing.partition("\n")
        unchanged_generated = header == MARKER + hashlib.sha256(body.encode()).hexdigest()
        # Adopt the original hand-written setup only if its values match exactly.
        equivalent = tomllib.loads(existing) == tomllib.loads(desired)
        if not unchanged_generated and not equivalent:
            raise ValueError(
                f"Preserving customized {target}. Back it up and move it aside, "
                "then rerun the Codex setup and merge your customizations manually."
            )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(desired)
    return target


if __name__ == "__main__":
    try:
        print(f"Codex configuration ready: {configure(ROOT)}")
    except (ValueError, OSError) as error:
        raise SystemExit(str(error)) from error
